export const getFeatured = () => catalog.filter((item) => item.featured);
export const getTrending = () => catalog.filter((item) => item.trending);
export const getNewReleases = () => catalog.filter((item) => item.newRelease);
export const getMovies = () => catalog.filter((item) => item.type === "movie");
export const getSeries = () => catalog.filter((item) => item.type === "series");
export const getById = (id) => catalog.find((item) => item.id === parseInt(id));
export const searchCatalog = (query) => {
  const q = query.toLowerCase();
  return catalog.filter(
    (item) =>
      item.title.toLowerCase().includes(q) ||
      item.genre.some((g) => g.toLowerCase().includes(q)) ||
      item.description.toLowerCase().includes(q)
  );
};
export const getByGenre = (genre) => {
  if (genre === "Tutti") return catalog;
  return catalog.filter((item) => item.genre.includes(genre));
};
